import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { launch } from './browser.mjs'

const root = new URL('../shots/windows-redesign/', import.meta.url)
await mkdir(root, { recursive: true })
const base = process.env.STAGESHOW_URL || 'http://127.0.0.1:4280'
const browser = await launch()
const checks = []
const errors = []
const check = (value, label) => { assert.ok(value, label); checks.push(label) }
const capture = (page, name) => page.screenshot({ path: new URL(name, root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true })
let failure
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1040 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/?workbench`)
  await page.waitForSelector('.lw-task-row')
  const rows = page.locator('.lw-task-row')
  check(await rows.count() === 8, 'initial task list shows eight active tasks')
  check(await rows.first().getAttribute('data-testid') === 'task-3', 'priority puts the overdue task first')
  check(await page.title() === '聚合平台 · Stageshow 界面预览', 'preview has a recognizable document title')
  check(await page.locator('.wb-label').textContent().then(t => t.includes('STAGESHOW')), 'host visibly names Stageshow')
  await page.getByLabel('搜索任务', { exact: true }).fill('数据结构')
  check(await rows.count() === 2, 'search matches course names')
  await page.getByLabel('搜索任务', { exact: true }).fill('不存在的任务')
  check(await rows.count() === 0 && await page.locator('.lw-empty').first().isVisible(), 'empty search presents recovery')
  check(await page.getByTestId('official').count() === 0, 'empty search removes stale task actions')
  await capture(page, 'preview-empty.png')
  await page.getByRole('button', { name: '查看全部任务', exact: true }).click()
  check(await rows.count() === 12, 'empty-state recovery clears search and filters')
  await page.getByLabel('任务排序').selectOption('deadline')
  check(await rows.first().getAttribute('data-testid') === 'task-12', 'deadline order uses actual dates')
  await page.getByLabel('任务排序').selectOption('priority')
  check(await rows.first().getAttribute('data-testid') === 'task-3', 'priority keeps pending work ahead of completed work')
  await page.getByTestId('task-1').click()
  const originalState = await page.locator('.lw-detail-facts > div').nth(1).textContent()
  await page.getByTestId('complete').click()
  check(await page.locator('.lw-detail-facts > div').first().textContent().then(t => t.includes('已完成')), 'completion updates selected task')
  check(await page.locator('.lw-detail-facts > div').nth(1).textContent() === originalState, 'manual completion retains original platform status')
  await page.getByTestId('complete').click()
  check(await page.locator('.lw-detail-facts > div').first().textContent().then(t => !t.includes('已完成')), 'completion can be restored')
  await page.getByRole('tab', { name: '已完成', exact: true }).click()
  check(await rows.count() === 4, 'completed filter includes only completed work')
  await page.locator('.lw-platforms .ss-row').filter({ has: page.getByText('PTA', { exact: true }) }).click()
  check(await rows.count() === 1, 'platform and status filters compose')
  await page.getByRole('button', { name: '管理已选课程', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox').filter({ hasText: '数据结构' }).click()
  await dialog.getByLabel('管理课程的平台').selectOption('学习通')
  await dialog.getByRole('checkbox').filter({ hasText: '高等数学' }).press('Space')
  await dialog.getByRole('button', { name: '保存选择', exact: true }).click()
  await page.getByRole('button', { name: '管理已选课程', exact: true }).click()
  await dialog.getByLabel('管理课程的平台').selectOption('学习通')
  check(await dialog.getByRole('checkbox').getAttribute('aria-checked') === 'true', 'course selections persist when reopening')
  await dialog.getByLabel('管理课程的平台').selectOption('PTA')
  check(await dialog.getByRole('checkbox').filter({ hasText: '数据结构' }).getAttribute('aria-checked') === 'false', 'unchecked course remains unchecked across platforms')
  await dialog.getByRole('checkbox').filter({ hasText: '数据结构' }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '管理已选课程', exact: true }).click()
  check(await dialog.getByRole('checkbox').filter({ hasText: '数据结构' }).getAttribute('aria-checked') === 'false', 'cancel discards unsaved course changes')
  await capture(page, 'preview-courses.png')
  await dialog.getByRole('button', { name: '关闭面板' }).focus()
  await page.keyboard.press('Shift+Tab')
  check(await dialog.getByRole('button', { name: '保存选择', exact: true }).evaluate(el => el === document.activeElement), 'dialog traps reverse tab at its first control')
  await page.keyboard.press('Tab')
  check(await dialog.getByRole('button', { name: '关闭面板' }).evaluate(el => el === document.activeElement), 'dialog traps tab at its last control')
  await page.keyboard.press('Escape')
  check(await dialog.count() === 0, 'Escape closes the dialog')
  await page.getByTestId('add').focus()
  await page.keyboard.press('Enter')
  check(await dialog.isVisible(), 'keyboard activates add task')
  check(await dialog.getByRole('button', { name: '添加任务', exact: true }).getAttribute('aria-disabled') === 'true', 'blank task title cannot be added')
  await dialog.getByLabel('任务名称', { exact: true }).fill('整理第六章笔记')
  await dialog.getByLabel('所属课程', { exact: true }).fill('数据结构')
  await dialog.getByRole('button', { name: '添加任务', exact: true }).click()
  check(await rows.count() === 9 && await page.locator('.lw-detail-title').textContent() === '整理第六章笔记', 'new task resets incompatible filters and selects the added task')
  const inView = await page.getByTestId('task-13').evaluate(el => {
    const row = el.getBoundingClientRect(), list = el.parentElement.getBoundingClientRect()
    return row.top >= list.top - 1 && row.bottom <= list.bottom + 1
  })
  check(inView, 'new task is scrolled fully into the task list')
  await capture(page, 'preview-added.png')
  await page.getByTestId('sync').click()
  check(await page.getByTestId('sync').getAttribute('aria-disabled') === 'true', 'sync is disabled while running')
  await page.waitForFunction(() => document.querySelector('[data-testid="sync"]')?.getAttribute('aria-disabled') === 'false')
  check(await rows.count() === 9, 'sync demonstration retains manual tasks')
  await page.getByTestId('official').click()
  check(await page.locator('.lw-toast-wrap').textContent().then(t => t.includes('演示任务没有真实链接')), 'demo official action explains its lack of live data')
  await page.getByRole('button', { name: '重置演示', exact: true }).click()
  check(await rows.count() === 8 && await page.getByTestId('task-13').count() === 0, 'host reset restores the initial scene')
  await capture(page, 'preview-desktop.png')
  await page.getByRole('button', { name: '窄屏', exact: true }).click()
  await page.waitForSelector('.lw-mobile-platform')
  check(await page.locator('.lw-sidebar').count() === 0, 'host compact mode uses its independent layout')
  await page.getByTestId('task-1').focus()
  await page.keyboard.press('Enter')
  check(await page.getByRole('button', { name: '返回清单', exact: true }).isVisible(), 'compact task opens a separate detail view')
  await page.getByRole('button', { name: '返回清单', exact: true }).click()
  check(await page.locator('.lw-main').isVisible(), 'compact back action restores the list')
  await page.close()
  for (const width of [390, 358]) {
    const compact = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' })
    compact.on('pageerror', error => errors.push(error.message))
    await compact.goto(`${base}/?workbench`)
    await compact.waitForSelector('.lw-mobile-platform')
    check(await compact.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px host has no horizontal overflow`)
    await compact.getByLabel('筛选平台', { exact: true }).selectOption('PTA')
    check(await compact.locator('.lw-task-row').count() === 2, `${width}px platform filter works`)
    await compact.getByTestId('task-1').click()
    await capture(compact, `preview-${width}-detail.png`)
    await compact.getByTestId('complete').click()
    check(await compact.locator('.lw-main').isVisible() && await compact.locator('.lw-task-row').count() === 1, `${width}px completion returns to the updated list`)
    await compact.getByRole('button', { name: '管理课程', exact: true }).click()
    check(await compact.getByRole('dialog').isVisible(), `${width}px course manager opens`)
    await capture(compact, `preview-${width}-courses.png`)
    await compact.keyboard.press('Escape')
    await compact.getByRole('button', { name: '重置演示', exact: true }).click()
    await capture(compact, `preview-${width}.png`)
    await compact.close()
  }
  const direct = await browser.newPage({ viewport: { width: 1200, height: 900 }, reducedMotion: 'reduce' })
  await direct.goto(`${base}/?capture=learning-workbench`)
  await direct.waitForSelector('.lw-task-row')
  check(await direct.locator('.lw-task-row').count() === 8, 'direct scene and reduced motion retain the complete poster')
  await direct.goto(`${base}/?example=learning-workbench`)
  const embedded = direct.frameLocator('iframe')
  await embedded.locator('.lw-task-row').first().waitFor()
  check(await embedded.locator('.lw-workbench').isVisible(), 'original Stageshow viewer loads the workbench')
  check(errors.length === 0, 'all preview interactions run without page errors')
} catch (error) { failure = error.stack || String(error) }
finally {
  await browser.close()
  await writeFile(new URL('interaction-checks.json', root), JSON.stringify({ outcome: failure ? 'failed' : 'passed', checks: checks.length, labels: checks, errors, failure }, null, 2))
}
if (failure) { console.error(failure); process.exitCode = 1 }
else console.log(`PASS: ${checks.length} Stageshow interaction checks`)
